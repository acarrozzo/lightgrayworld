/**
 * Writes two cut-down copies of enemies.js for the browser, which must not
 * carry the whole registry (145 KB of descriptions, drop tables and rewards):
 *
 * - src/lib/game-data/bosses.generated.js: the enemies tagged `rank` (boss or
 *   miniboss), with everything the battle HUD and the World map need to draw
 *   one — portrait, stats, perk flags, lair.
 * - src/lib/game-data/roster.generated.js: every enemy, name and numbers only —
 *   what the Kill List needs to draw its boxes (area, level, rank, rare, tone)
 *   and the bestiary card its header. Prose, loot and perks stay on the server
 *   and come down with the card's record.
 *
 * Run: npm run generate-bosses   (dev and build run it for you)
 * test/boss-teleports.test.js and test/kill-list.test.ts fail when a file is stale.
 */
const fs = require('fs')
const path = require('path')
const { ENEMIES } = require('../src/lib/game-data/enemies')

/** What stays off the boss record: prose, loot and rewards. Everything else rides. */
const OMIT = new Set(['description', 'drops', 'xpReward', 'goldMin', 'goldMax'])

function buildBosses(enemies = ENEMIES) {
  return enemies
    .filter((enemy) => enemy.rank)
    .map((enemy) => Object.fromEntries(Object.entries(enemy).filter(([key]) => !OMIT.has(key))))
}

function render(bosses) {
  const rows = bosses.map((boss) => `  ${JSON.stringify(boss)},`).join('\n')
  return `// GENERATED by scripts/generate-bosses.js from enemies.js — do not edit.
// The enemies tagged \`rank\` (boss / miniboss), minus prose, loot and rewards,
// so the browser can draw a boss without the whole enemy registry.
const BOSSES = [
${rows}
]

module.exports = { BOSSES }
`
}

/** The roster's columns, in the order they are written. Absent fields are left out. */
const ROSTER_KEEP = [
  'slug', 'name', 'zone', 'area', 'level', 'rank', 'lair', 'rare', 'nameTone', 'icon',
  'damageType', 'isAggressive', 'isFlying', 'isFriendly', 'hp', 'att', 'def',
]

function buildRoster(enemies = ENEMIES) {
  return enemies.map((enemy) =>
    Object.fromEntries(ROSTER_KEEP.filter((key) => enemy[key] !== undefined).map((key) => [key, enemy[key]]))
  )
}

function renderRoster(roster) {
  const rows = roster.map((enemy) => `  ${JSON.stringify(enemy)},`).join('\n')
  return `// GENERATED by scripts/generate-bosses.js from enemies.js — do not edit.
// Every enemy, name and numbers only — area, level, rank, rare and the Kill
// List's name tone — so the browser can draw the Kill List and a bestiary
// card's header without the whole enemy registry.
const ENEMY_ROSTER = [
${rows}
]

module.exports = { ENEMY_ROSTER }
`
}

const OUT = path.join(__dirname, '../src/lib/game-data/bosses.generated.js')
const ROSTER_OUT = path.join(__dirname, '../src/lib/game-data/roster.generated.js')

if (require.main === module) {
  fs.writeFileSync(OUT, render(buildBosses()))
  console.log(`bosses: wrote ${buildBosses().length} to ${path.relative(process.cwd(), OUT)}`)
  fs.writeFileSync(ROSTER_OUT, renderRoster(buildRoster()))
  console.log(`roster: wrote ${buildRoster().length} to ${path.relative(process.cwd(), ROSTER_OUT)}`)
}

module.exports = { buildBosses, render, OUT, buildRoster, renderRoster, ROSTER_OUT, ROSTER_KEEP }
